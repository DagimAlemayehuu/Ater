def validate_yaml_frontmatter(meta: Dict[str, Any], raw_note_content: str, note_title_for_log: str, note_type_for_log: str, all_notes_metadata: List[Dict[str, Any]]) -> List[str]:
    """
    Validates the YAML frontmatter of a single note.
    Returns a list of errors.
    """
    errors: List[str] = []

    # Check for required universal fields
    required_fields = ["title", "created_at", "last_modified", "deployment_batch_id", "uid",
                       "type", "course", "year", "semester", "credits", "original_source", "aliases"]
    for field in required_fields:
        if field not in meta:
            errors.append(f"Missing required field '{field}'.")
    
    # Validate specific field types and formats
    if "title" in meta:
        title = meta["title"]
        if not isinstance(title, str) or not vault_utils.get_canonical_title(title) == title:
            errors.append(f"'title' field '{title}' is not a canonical, underscore-separated, Title_Case string. Expected: '{vault_utils.get_canonical_title(title)}'.")
        if re.search(r"[\(\)]", title):
            errors.append(f"'title' field '{title}' contains prohibited parentheses '()'.")

    if "type" in meta and meta["type"] not in EXPECTED_H1_SECTIONS:
        errors.append(f"'type' field '{meta['type']}' is not a recognized type.")
    
    # Validate canonicalization of year, semester, course
    for field in ["year", "semester", "course"]:
        if field in meta:
            value = meta[field]
            if not isinstance(value, str) or not vault_utils.get_canonical_title(value) == value:
                errors.append(f"'{field}' field '{value}' is not canonical. Expected: '{vault_utils.get_canonical_title(value)}'.")
            if re.search(r"[\(\)]", value):
                errors.append(f"'{field}' field '{value}' contains prohibited parentheses '()'.")


    if "credits" in meta and not isinstance(meta["credits"], int):
        errors.append(f"'credits' field '{meta['credits']}' is not an integer.")

    if "aliases" in meta:
        if not isinstance(meta["aliases"], list):
            errors.append(f"'aliases' field is not a list.")
        else:
            for alias in meta["aliases"]:
                if not isinstance(alias, str) or not vault_utils.get_canonical_title(alias) == alias:
                    errors.append(f"Alias '{alias}' is not a canonical, underscore-separated, Title_Case string. Expected: '{vault_utils.get_canonical_title(alias)}'.")
                if re.search(r"[\(\)]", alias):
                    errors.append(f"Alias '{alias}' contains prohibited parentheses '()'.")

    # Type-specific field checks
    if note_type_for_log == "Unit":
        if "unit" in meta:
            errors.append(f"(type: Unit) has an unexpected 'unit' field. Unit notes should not have a unit field.")
        if "parent" in meta:
            errors.append(f"(type: Unit) has an unexpected 'parent' field. Unit notes should not have a parent.")
        if not note_title_for_log.endswith("_Hub"):
             errors.append(f"(type: Unit) title does not end with '_Hub'.")
    
    elif note_type_for_log == "Foundational":
        if "unit" not in meta:
            errors.append(f"(type: Foundational) is missing required 'unit' field.")
        else:
            unit_title = meta["unit"]
            if not isinstance(unit_title, str) or not vault_utils.get_canonical_title(unit_title) == unit_title:
                errors.append(f"(type: Foundational) 'unit' field '{unit_title}' is not canonical. Expected: '{vault_utils.get_canonical_title(unit_title)}'.")
            if re.search(r"[\(\)]", unit_title):
                errors.append(f"(type: Foundational) 'unit' field '{unit_title}' contains prohibited parentheses '()'.")
            if not any(vault_utils.get_canonical_title(n.get('title')) == vault_utils.get_canonical_title(unit_title) and n.get('type') == 'Unit' for n in all_notes_metadata):
                errors.append(f"(type: Foundational) 'unit' field '{unit_title}' refers to a non-existent or non-Unit type note.")
        if "parent" in meta:
            errors.append(f"(type: Foundational) has an unexpected 'parent' field. Foundational notes should not have a parent.")
        
    elif note_type_for_log == "Core":
        if "unit" not in meta:
            errors.append(f"(type: Core) is missing required 'unit' field.")
        else:
            unit_title = meta["unit"]
            if not isinstance(unit_title, str) or not vault_utils.get_canonical_title(unit_title) == unit_title:
                errors.append(f"(type: Core) 'unit' field '{unit_title}' is not canonical. Expected: '{vault_utils.get_canonical_title(unit_title)}'.")
