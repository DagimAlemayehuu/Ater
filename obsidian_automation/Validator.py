def _validate_single_markdown_table(table_lines: List[str], note_title: str, table_start_line_in_body: int) -> List[str]:
    """
    Validates the structure and formatting of a single Markdown table block.
    `table_start_line_in_body` is the line number where the table begins *within the body_content*.
    """
    table_errors: List[str] = []

    if len(table_lines) < 2:
        table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}: Table is too short (needs at least header and separator).")
        return table_errors

    # Extract header and separator, assuming they are the first two lines
    header_line_str = table_lines[0] # CRITICAL FIX: Access list elements directly
    separator_line_str = table_lines[1] # CRITICAL FIX: Access list elements directly

    # 1. Basic check for pipes
    if not (header_line_str.strip().startswith('|') and header_line_str.strip().endswith('|') and
            separator_line_str.strip().startswith('|') and separator_line_str.strip().endswith('|')):
        table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}: Missing outer pipes in header or separator. Header: '{header_line_str.strip()}', Separator: '{separator_line_str.strip()}'.")
        # Attempt to proceed by forcing pipe splitting for subsequent checks
        header_parts = [h.strip() for h in header_line_str.split('|')]
        separator_parts = [s.strip() for s in separator_line_str.split('|')]
    else:
        header_parts = [h.strip() for h in header_line_str.split('|')]
        separator_parts = [s for s in separator_line_str.split('|')] # Don't strip separators yet for proper alignment check

    # Filter out empty strings from split (due to leading/trailing pipes)
    headers = [h for h in header_parts if h]
    separators = [s for s in separator_parts if s.strip()] # Strip here for length check

    if len(headers) != len(separators):
        table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}: Mismatched number of headers ({len(headers)}) and separator columns ({len(separators)}).")
        return table_errors # Cannot proceed reliably with column-specific checks

    num_columns = len(headers)
    
    # 2. Check separator format (---, :---, ---:, :---:)
    alignment_types = []
    min_column_visual_widths = [len(h) for h in headers] # Start with header width
    
    for col_idx, sep in enumerate(separators):
        stripped_sep = sep.strip()
        if not re.match(r":?-{3,}:?", stripped_sep):
            table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 2}, column {col_idx + 1}: Invalid separator format '{stripped_sep}'. Must be :---, ---:, or :---: (3+ hyphens).")
        
        if stripped_sep.startswith(':') and stripped_sep.endswith(':'):
            alignment_types.append('center')
        elif stripped_sep.endswith(':'):
            alignment_types.append('right')
        elif stripped_sep.startswith(':'):
            alignment_types.append('left')
        else:
            alignment_types.append('left') # Default to left if no explicit markers
        
        min_column_visual_widths[col_idx] = max(min_column_visual_widths[col_idx], len(stripped_sep))

    # 3. Validate data rows & update min_column_visual_widths
    for row_idx, line in enumerate(table_lines[2:]): # Start from the third line (after header and separator)
        line_num_in_body = table_start_line_in_body + 3 + row_idx
        stripped_line = line.strip()

        if not (stripped_line.startswith('|') and stripped_line.endswith('|')):
            table_errors.append(f"Table in '{note_title}' at body line {line_num_in_body}: Data row is missing outer pipes. Line: '{line}'.")
            continue

        cells_with_pipes = stripped_line.split('|')
        cells = [c.strip() for c in cells_with_pipes if c.strip()] # Filter empty strings from splits

        if len(cells) != num_columns:
            table_errors.append(f"Table in '{note_title}' at body line {line_num_in_body}: Mismatched number of cells ({len(cells)}) vs header columns ({num_columns}). Line: '{line}'.")
            continue

        for col_idx, cell_content in enumerate(cells):
            # Update min_column_visual_widths based on cell content
            min_column_visual_widths[col_idx] = max(min_column_visual_widths[col_idx], len(cell_content))

            # Check for emojis (prohibited)
            emoji_pattern = re.compile(r"[\U0001F600-\U0001F64F\U0001F300-\U0001F5FF\U0001F680-\U0001F6FF\U0001F1E0-\U0001F1FF\U00002702-\U000027B0]")
            if emoji_pattern.search(cell_content):
                table_errors.append(f"Table in '{note_title}' at body line {line_num_in_body}, column {col_idx + 1}: Emojis are strictly prohibited in table cells. Content: '{cell_content}'.")

            # Multi-line cell rules:
            if len(cell_content) > 50 and "<br>" not in cell_content:
                table_errors.append(f"Table in '{note_title}' at body line {line_num_in_body}, column {col_idx + 1}: Cell content is long ({len(cell_content)} chars) but missing `<br>` for multi-line formatting. Content: '{cell_content[:50]}...'.")
    
    # 4. Consistent Column Widths (Alignment of pipes)
    # This check is complex to do purely on original lines with varying inner whitespace.
    # We rely on previous checks for pipe presence and consistent column count.
    # The "equal column widths" is more of a rendered visual aesthetic achieved by padding.

    # 5. Check for table title being inside table (prohibited)
    # This checks header cells specifically for any H-level markdown.
    for cell in headers:
        if re.match(r"^#+\s*", cell):
            table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}: Table title found *inside* the table header, which is prohibited. Table titles must be above the table.")
            break

    # 6. Alignment Rules heuristic
    header_texts_lower = [h.lower() for h in headers]
    for col_idx, header_text in enumerate(header_texts_lower):
        actual_alignment = alignment_types[col_idx]
        
        if ("item" in header_text or "text" in header_text or "description" in header_text) and actual_alignment != "left":
            table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}, column {col_idx + 1} ('{headers[col_idx]}'): Header implies left alignment but has '{actual_alignment}' marker in separator.")
        elif ("number" in header_text or "value" in header_text or "count" in header_text) and actual_alignment != "right":
            table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}, column {col_idx + 1} ('{headers[col_idx]}'): Header implies right alignment but has '{actual_alignment}' marker in separator.")
        elif ("category" in header_text or "label" in header_text) and actual_alignment != "center":
            table_errors.append(f"Table in '{note_title}' at body line {table_start_line_in_body + 1}, column {col_idx + 1} ('{headers[col_idx]}'): Header implies center alignment but has '{actual_alignment}' marker in separator.")

    return table_errors


def _validate_boxed_formula_latex(latex_block_content: str, note_title: str, line_start_idx: int) -> List[str]:
    """
    Validates the specific rules for LaTeX boxed formulas within a $$...$$ block.
    Assumes `latex_block_content` includes the `$$` delimiters.
    """
    latex_errors: List[str] = []
    
    # Remove outer $$ for inner content processing
    inner_content = latex_block_content.strip()
    if not (inner_content.startswith('$$') and inner_content.endswith('$$')):
        latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}: '$$' markers are missing or malformed. Content: '{latex_block_content[:50].replace('\n', ' ')}...'.")
        return latex_errors # Cannot parse inner content reliably

    # Extract content between $$
    inner_content = inner_content[2:-2].strip()

    boxed_matches = list(re.finditer(r"\\boxed\{(.*?)\}", inner_content, re.DOTALL))

    # Check for simple numerical answers that should be plain text, unless part of a larger boxed/aligned structure
    if not boxed_matches and not re.search(r"\\begin\{aligned\}", inner_content):
        if re.fullmatch(r"[\d.,\s]+\s*\\?(?:[a-zA-Z]+)?", inner_content.strip()):
            latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}: Simple numerical answers must be plain text, NOT within a `$$...$$` block. Content: '{inner_content}'.")
        return latex_errors # If no boxes and not aligned, other checks are irrelevant here

    if len(boxed_matches) > 1:
        # Check for `\qquad` separation between multiple boxes
        if not re.search(r"\\boxed\{.*?\}\s*\\qquad\s*\\boxed\{.*?\}", inner_content, re.DOTALL):
            latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}: Multiple `\\boxed{{}}` environments must be separated by `\\qquad`. Found content between boxes that is not `\\qquad`.")
        else:
            # Check for similar structure with `\qquad`
            two_boxes_match = re.match(r"\\boxed\{(.*?)\}\s*\\qquad\s*\\boxed\{(.*?)\}", inner_content, re.DOTALL)
            if two_boxes_match:
                box1_content = two_boxes_match.group(1)
                box2_content = two_boxes_match.group(2)
                # Simple heuristic for "similar structure": count non-whitespace/alphanumeric characters
                ops1 = len(re.findall(r"[^a-zA-Z0-9\s]", box1_content))
                ops2 = len(re.findall(r"[^a-zA-Z0-9\s]", box2_content))
                if abs(ops1 - ops2) > 3: # Allow some deviation but flag large differences
                    latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}: Side-by-side boxed formulas with `\\qquad` appear to have dissimilar structure. Review '{box1_content[:20].replace('\n', ' ')}...' and '{box2_content[:20].replace('\n', ' ')}...'.")

    for match_idx, match in enumerate(boxed_matches):
        boxed_inner_content = match.group(1).strip()
        
        # `\displaystyle` Requirement: Presence of `\displaystyle` (unless `\textbf` for theorems)
        if r'\displaystyle' not in boxed_inner_content and r'\textbf' not in boxed_inner_content:
            latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}, box {match_idx + 1}: Missing `\\displaystyle` inside `\\boxed{{}}` (unless it's a theorem/definition box). Content: '{boxed_inner_content}'.")

        # Explanation Word Limits and Punctuation for `\quad \text{(Explanation)}`
        explanation_in_box_match = re.search(r"\\quad\\text\{\s*\(.+?\)\s*\}$", boxed_inner_content)
        if explanation_in_box_match: # This looks for text *inside* the boxed content with \quad\text
            explanation_text = explanation_in_box_match.group(1).strip()
            words = explanation_text.split()
            if len(words) > 5:
                latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}, box {match_idx + 1}: Explanation inside `\\text{{}}` within `\\boxed{{}}` should be max 5 words. Found '{explanation_text}' ({len(words)} words).")
            if re.search(r"[.?!]", explanation_text):
                latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}, box {match_idx + 1}: Explanation inside `\\text{{}}` within `\\boxed{{}}` must not be a full sentence (contains punctuation). Content: '{explanation_text}'.")
        
        # `\begin{aligned}` Placement: correctly wrapped *immediately inside* `\boxed{}` for final boxed derivations
        if r'\begin{aligned}' in boxed_inner_content and not boxed_inner_content.strip().startswith(r'\begin{aligned}'):
            latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}, box {match_idx + 1}: `\\begin{{aligned}}` found within `\\boxed{{}}` but not starting immediately after `\\boxed{{}}`. Should be `\\boxed{{\\begin{{aligned}}...`. Content: '{boxed_inner_content[:50].replace('\n', ' ')}...'.")

    # Check for excessive double boxing
    double_boxed_pattern = re.compile(r"\\fbox\{\\boxed\{\\displaystyle (.+?)\}\}", re.DOTALL)
    if len(list(double_boxed_pattern.finditer(inner_content))) > 1:
        latex_errors.append(f"LaTeX block in '{note_title}' at line {line_start_idx}: Only a maximum of one `\\fbox{{\\boxed{{}}}}` instance is permitted per note. Found multiple.")
    
    return latex_errors


def _validate_concept_questions_section(section_content: str, note_title: str, expected_heading_level: str, expected_concept_type: str, all_notes_metadata: List[Dict[str, Any]], section_start_line_in_body: int) -> List[str]:
    """
    Helper function to validate question blocks within a Foundational, Core, or Supporting section.
    """
    section_errors: List[str] = []

    # Pattern to find '### [[Concept]] Questions' or '##### [[Concept]] Questions'
    concept_questions_h_pattern = re.compile(rf"^{expected_heading_level}\s*\[\[([^\]]+?)\]\] Questions\s*$", re.MULTILINE)
    
    found_concept_blocks = False
    for h_match in concept_questions_h_pattern.finditer(section_content):
        found_concept_blocks = True
        concept_link = h_match.group(1).strip()
        
        # Check canonicalization of concept link
        if not vault_utils.get_canonical_title(concept_link) == concept_link:
            section_errors.append(f"Concept link '[[{concept_link}]]' in '{expected_heading_level} Questions' heading is not canonical. Expected: '[[{vault_utils.get_canonical_title(concept_link)}]]'.")
        
        # Check if the linked concept exists and is of the expected type
        concept_exists = any(vault_utils.get_canonical_title(m.get("title")) == vault_utils.get_canonical_title(concept_link) and m.get("type") == expected_concept_type for m in all_notes_metadata if m.get("title"))
        if not concept_exists:
            section_errors.append(f"Concept '[[{concept_link}]]' in '{expected_heading_level} Questions' heading links to a non-existent or non-{expected_concept_type} type note.")
        
        # Extract the content of this concept's question block
        # This regex captures everything after the heading until the next heading of same/higher level, or '---', or end of section
        q_block_start_idx = h_match.end()
        # Adjusted regex to handle either a higher level heading (like '##' or '####')
        # or a '---' or end of section.
        next_heading_or_sep_match = re.search(rf"^\s*(?:#{{1,{len(expected_heading_level)}}}|#{{1,{len(expected_heading_level) - 1}}}|\n---)", section_content[q_block_start_idx:], re.MULTILINE)
        
        if next_heading_or_sep_match:
            questions_text = section_content[q_block_start_idx : q_block_start_idx + next_heading_or_sep_match.start()]
        else:
            questions_text = section_content[q_block_start_idx:]
        
        section_errors.extend(_validate_individual_question_block(
            concept_link=concept_link,
            questions_text=questions_text,
            note_title=note_title,
            all_notes_metadata=all_notes_metadata,
            section_start_line_in_body=section_start_line_in_body + section_content[:h_match.start()].count('\n') + 1 # Adjust for concept heading offset
        ))
    
    if not found_concept_blocks:
        section_errors.append(f"Section for '{expected_concept_type} Concepts' is missing any '{expected_heading_level} [[Concept]] Questions' sub-sections.")

    return section_errors


def _validate_individual_question_block(concept_link: str, questions_text: str, note_title: str, all_notes_metadata: List[Dict[str, Any]], section_start_line_in_body: int) -> List[str]:
    """Helper to validate a single block of questions for one concept (main questions + sub-questions)."""
    block_errors = []
    
    # Split into individual main questions using #. as delimiter
    # This pattern needs to be careful not to split sub-questions.
    # It looks for '#. Type: [[...]]' followed by content until the next '#. Type:' or end of string.
    main_question_blocks = re.finditer(r"(^\s*#\.\s*Type:\s*\[\[([^\]]+?)\]\]\s*(.+?)(?=\n\s*#\.|\n---|\Z))", questions_text, re.DOTALL | re.MULTILINE)
    
    current_q_num = 1
    found_main_questions = False
    
    for q_match in main_question_blocks:
        found_main_questions = True
        full_q_block_raw = q_match.group(0) # The entire matched question block
        
        # Extract the type tag link from the matched block
        type_tag_link_match = re.search(r"Type:\s*\[\[([^\]]+?)\]\]", full_q_block_raw)
        type_tag_link = type_tag_link_match.group(1).strip() if type_tag_link_match else "N/A_Link"
        
        # Validate "Type: [[Canonical_Concept_Title]]" tag
        if not type_tag_link == concept_link:
            block_errors.append(f"Main question tag 'Type: [[{type_tag_link}]]' does not match block's concept '[[{concept_link}]]' (Main Q {current_q_num}).")
        
        # Check numbering (the #. part)
        full_q_block_lines = full_q_block_raw.splitlines()
        # Corrected: check only the first line of the question block
        if full_q_block_lines and not full_q_block_lines[0].strip().startswith(f"{current_q_num}. Type: [[{type_tag_link}]]"):
             block_errors.append(f"Main question for '[[{concept_link}]]' at question number {current_q_num} is not correctly numbered or formatted. Expected '{current_q_num}. Type: [[...]]'. Found: '{full_q_block_lines[0].strip() if full_q_block_lines else 'Empty'}'.")

        # Validate sub-questions (a), (b), (c)
        sub_questions_matches = re.finditer(r"^\s*\((\w)\)\s*(.*?)(?=\n\s*\(\w\)|\n\s*#\.|\n---|\Z)", full_q_block_raw, re.DOTALL | re.MULTILINE)
        
        current_sub_q_letter_code = ord('a')
        found_sub_questions = False
        for sub_q_match in sub_questions_matches:
            found_sub_questions = True
            letter = sub_q_match.group(1)
            sub_q_content = sub_q_match.group(2).strip()

            if letter != chr(current_sub_q_letter_code):
                block_errors.append(f"Sub-question for '[[{concept_link}]]' (Main Q {current_q_num}) out of order. Expected '({chr(current_sub_q_letter_code)})', Found '({letter})'.")
            
            if not sub_q_content:
                block_errors.append(f"Sub-question '({letter})' for '[[{concept_link}]]' (Main Q {current_q_num}) is empty.")

            current_sub_q_letter_code += 1
        
        if not found_sub_questions:
            block_errors.append(f"Main question {current_q_num} for '[[{concept_link}]]' has no sub-questions (a), (b), etc.")

        current_q_num += 1
    
    if not found_main_questions:
        block_errors.append(f"Concept '[[{concept_link}]]' section contains no main questions formatted with '#. Type: [[...]]'.")

    return block_errors


